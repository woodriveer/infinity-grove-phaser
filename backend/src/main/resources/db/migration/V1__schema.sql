-- The whole schema. Hibernate only validates it (ddl-auto: validate): column names and types follow the entities.
-- Every reference is a foreign key: rows owned by a player cascade with the user, references to a catalog restrict.
-- PostgreSQL 16 SQL only (docker-compose runs 16, the tests run 17).

create table users (
    username      varchar(255) primary key,
    password      varchar(255) not null,
    created_at    bigint       not null,
    last_login_at bigint       not null
);

create table refresh_tokens (
    token_hash varchar(255) primary key,
    username   varchar(255) not null references users (username) on delete cascade,
    expires_at bigint       not null,
    revoked    boolean      not null
);

create index idx_refresh_tokens_username on refresh_tokens (username);

create table heroes (
    id           varchar(255) primary key,
    name         varchar(255) not null,
    hero_class   varchar(255) not null,
    element      varchar(32)  not null,
    leader_bonus varchar(512) not null,
    portrait     varchar(255) not null,
    sort_order   integer      not null
);

create table hero_skills (
    id               varchar(255)  primary key,
    hero_id          varchar(255)  not null references heroes (id) on delete restrict,
    slot             integer       not null,
    name             varchar(255)  not null,
    skill_type       varchar(255)  not null,
    effect           varchar(1024) not null,
    cooldown_seconds integer       not null,
    image            varchar(255)  not null
);

create index idx_hero_skills_hero_id on hero_skills (hero_id);

-- Copper per kill (min..max) and the fastest honest time between kills. The id is chosen by the seed or the operator.
create table drop_rules (
    id               integer primary key,
    min_copper       integer not null check (min_copper >= 1),
    max_copper       integer not null,
    kill_interval_ms bigint  not null check (kill_interval_ms >= 1),
    constraint ck_drop_rules_range check (max_copper >= min_copper)
);

-- One row per distinct enemy attribute set; stages and chapters share them.
create table enemies (
    id               bigint generated by default as identity primary key,
    element          varchar(32) not null check (element in ('FIRE', 'WATER', 'NATURE', 'LIGHT', 'DARKNESS')),
    physical_defense integer     not null check (physical_defense between 0 and 90),
    magical_defense  integer     not null check (magical_defense between 0 and 90),
    crit_resistance  integer     not null check (crit_resistance between 0 and 100),
    constraint uk_enemies_attributes unique (element, physical_defense, magical_defense, crit_resistance)
);

create table chapters (
    number             integer primary key,
    boss_health        integer not null,
    boss_time_limit_ms bigint  not null,
    boss_enemy_id      bigint  not null references enemies (id) on delete restrict,
    boss_drop_rule_id  integer not null references drop_rules (id) on delete restrict
);

create table stages (
    id                     varchar(255) primary key,
    chapter                integer      not null references chapters (number) on delete restrict,
    number                 integer      not null,
    phases_per_stage       integer      not null,
    monster_health         integer      not null,
    miniboss_health        integer      not null,
    miniboss_time_limit_ms bigint       not null,
    monster_enemy_id       bigint       not null references enemies (id) on delete restrict,
    miniboss_enemy_id      bigint       not null references enemies (id) on delete restrict,
    monster_drop_rule_id   integer      not null references drop_rules (id) on delete restrict,
    miniboss_drop_rule_id  integer      not null references drop_rules (id) on delete restrict,
    constraint uk_stages_chapter_number unique (chapter, number)
);

create index idx_stages_chapter on stages (chapter);

create table progress (
    username  varchar(255) primary key references users (username) on delete cascade,
    chapter   integer      not null,
    stage     integer      not null,
    encounter varchar(32)  not null,
    phase     integer      not null,
    completed boolean      not null,
    constraint fk_progress_stage foreign key (chapter, stage) references stages (chapter, number) on delete restrict
);

create table wallets (
    username varchar(255) primary key references users (username) on delete cascade,
    copper   bigint       not null
);

create table wallet_drop_queues (
    id                   varchar(255) primary key,
    username             varchar(255) not null references users (username) on delete cascade,
    drop_rule_id         integer      not null references drop_rules (id) on delete restrict,
    drops                varchar(512) not null,
    allowance            integer      not null,
    allowance_updated_at bigint       not null
);

create index idx_wallet_drop_queues_username on wallet_drop_queues (username);

create table player_cards (
    username         varchar(255) primary key references users (username) on delete cascade,
    starting_element varchar(32)  not null,
    leader_id        varchar(255) not null references heroes (id) on delete restrict,
    cleared_chapters varchar(64)  not null,
    wins_day         varchar(10),
    wins_today       integer      not null,
    last_farm_win_at bigint
);

create table card_copies (
    id       varchar(255) primary key,
    username varchar(255) not null references users (username) on delete cascade,
    hero_id  varchar(255) not null references heroes (id) on delete restrict,
    stars    integer      not null,
    copies   integer      not null
);

create index idx_card_copies_username on card_copies (username);

create table equipment_pieces (
    id         varchar(255) primary key,
    username   varchar(255) not null references users (username) on delete cascade,
    slot       varchar(16)  not null,
    rarity     varchar(16)  not null,
    base_click integer,
    refine     integer      not null,
    affixes    varchar(256) not null,
    hero_id    varchar(255) references heroes (id) on delete restrict,
    created_at bigint       not null
);

create index idx_equipment_pieces_username on equipment_pieces (username);
